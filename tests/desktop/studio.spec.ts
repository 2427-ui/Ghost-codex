import { test, expect, _electron as electron, type ElectronApplication } from '@playwright/test'
import { createRequire } from 'node:module'
import { resolve, join } from 'node:path'
import { mkdir, writeFile, readFile } from 'node:fs/promises'

const require = createRequire(import.meta.url)
test('Ghost desktop: editable persona, project editor, real Codex, mini window and restart', async () => {
  const directory = resolve('.ghost-dev/e2e-' + Date.now())
  const project = resolve('.ghost-dev/desktop-fixture')
  await mkdir(project, { recursive: true })
  await writeFile(join(project, 'hello.ts'), 'export const greeting = "你好，Ghost"\n')
  const env: Record<string, string> = { ...Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined)), GHOST_HOME: directory, GHOST_TEST: '1', GHOST_TEST_PROJECT: project }
  delete env.ELECTRON_RUN_AS_NODE
  let app: ElectronApplication | null = null
  const errors: string[] = []
  try {
    app = await electron.launch({ executablePath: require('electron'), args: ['.'], env })
    const page = await app.firstWindow()
    page.on('pageerror', error => errors.push(error.message))
    await expect(page.getByRole('heading', { name: 'GHOST.' })).toBeVisible()
    await mkdir(resolve('.ghost-dev/screenshots'), { recursive: true })
    await page.screenshot({ path: '.ghost-dev/screenshots/home.png' })
    await expect(page.locator('.projects-list').getByRole('button', { name: '测试项目', exact: true })).toBeVisible()
    await expect(page.locator('.dsh-fairy-main')).toHaveCount(1)
    expect((await page.evaluate(() => window.ghost.snapshot())).settings.fontSize).toBe(18)
    const originalTitleSize = await page.locator('.hero h1').evaluate(el => getComputedStyle(el).fontSize)
    await page.evaluate(() => window.ghost.settings({ fontSize: 20 }))
    await expect.poll(() => page.locator('.hero h1').evaluate(el => getComputedStyle(el).fontSize)).toBe(originalTitleSize)
    await page.evaluate(() => window.ghost.settings({ fontSize: 18 }))
    await mkdir(resolve('.ghost-dev/screenshots'), { recursive: true })
    await page.screenshot({ path: '.ghost-dev/screenshots/home.png' })
    await page.getByRole('button', { name: '本地工作空间' }).click()
    await page.getByLabel('角色指令').fill('你叫 Ghost。保持严谨，默认中文。')
    await page.getByRole('button', { name: '保存人设' }).click()
    await expect(page.getByRole('button', { name: '已保存', exact: true })).toBeVisible()
    await page.screenshot({ path: '.ghost-dev/screenshots/persona.png' })
    await page.getByRole('button', { name: '关闭设置' }).click()
    expect((await page.evaluate(() => window.ghost.snapshot())).settings.lastProjectId).toBe(null)
    await page.evaluate(() => window.ghost.connect())
    await expect(page.locator('.system-card')).toContainText('Codex 已连接', { timeout: 60000 })
    const shared = await page.evaluate(() => window.ghost.snapshot())
    expect(shared.historySync.state).toBe('ready')
    expect(shared.sessions.length).toBeGreaterThan(0)
    await page.getByLabel('发送给 Ghost 的任务').fill('只回复 GHOST_ORDINARY_OK，不要调用任何工具。')
    await page.getByRole('button', { name: '发送任务', exact: true }).click()
    await expect(page.locator('.message-agent .markdown')).toContainText('GHOST_ORDINARY_OK', { timeout: 90000 })
    await expect.poll(async () => (await page.evaluate(() => window.ghost.snapshot())).runtime.activity).toBe('completed')
    const chatId = await page.evaluate(async () => { const s = await window.ghost.snapshot(); return s.sessions.find(c => c.id === s.settings.lastSessionId)! })
    expect(chatId.projectId).toBe(null)
    await page.getByRole('button', { name: '迷你悬浮窗', exact: true }).click()
    const ordinaryPet = app.windows().find(window => window.url().includes('mini=1'))!
    await ordinaryPet.getByRole('button', { name: '展开桌宠对话' }).click()
    await expect(ordinaryPet.locator('.pet-context')).toContainText('普通聊天')
    await ordinaryPet.getByLabel('桌宠消息输入').fill('只回复 GHOST_ORDINARY_PET_OK，不调用任何工具。')
    await ordinaryPet.getByRole('button', { name: '发送桌宠消息' }).click()
    await expect(ordinaryPet.locator('.pet-message.from-ghost').filter({ hasText: 'GHOST_ORDINARY_PET_OK' })).toBeVisible({ timeout: 90000 })
    await expect.poll(async () => (await ordinaryPet.evaluate(() => window.ghost.snapshot())).runtime.activity).toBe('completed')
    await ordinaryPet.getByRole('button', { name: '打开完整工作台' }).click()
    await expect(page.locator('.message-agent .markdown').filter({ hasText: 'GHOST_ORDINARY_PET_OK' })).toBeVisible()
    await page.getByRole('button', { name: '同步本机历史' }).click()
    await expect.poll(async () => (await page.evaluate(() => window.ghost.snapshot())).historySync.state).toBe('ready')
    expect((await page.evaluate(() => window.ghost.snapshot())).sessions.find(s => s.id === chatId.id)?.projectId).toBe(null)
    await page.getByLabel('历史范围').selectOption('chat')
    await page.getByLabel('归档', { exact: true }).check()
    await expect.poll(async () => page.locator('.session-row').count()).toBeGreaterThan(0)
    await page.getByLabel('归档', { exact: true }).uncheck()
    await page.locator('.projects-list').getByRole('button', { name: '测试项目', exact: true }).click()
    await page.getByRole('button', { name: '打开项目文件' }).click()
    await page.getByRole('button', { name: 'hello.ts', exact: true }).click()
    await expect(page.locator('.monaco-editor')).toBeVisible()
    await expect(page.locator('.editor-status')).toContainText('已与磁盘同步')
    await page.screenshot({ path: '.ghost-dev/screenshots/workspace.png' })
    const content = await page.evaluate(async () => { const s = await window.ghost.snapshot(); return window.ghost.read(s.settings.lastProjectId!, 'hello.ts') })
    expect(content.content).toContain('你好，Ghost')
    await page.evaluate(async () => { const s = await window.ghost.snapshot(); const id = s.settings.lastProjectId!; const doc = await window.ghost.read(id, 'hello.ts'); await window.ghost.save(id, { ...doc, content: 'export const greeting = "edited"\n' }) })
    expect(await readFile(join(project, 'hello.ts'), 'utf8')).toContain('edited')
    await page.getByRole('button', { name: '重新载入文件' }).click()
    await page.getByRole('button', { name: '关闭工作区' }).click()
    const status = await page.evaluate(() => window.ghost.snapshot())
    expect(status.runtime.account?.type).toBe('chatgpt')
    await page.getByLabel('发送给 Ghost 的任务').fill('只回复 GHOST_DESKTOP_OK，不要调用任何工具。')
    await page.getByRole('button', { name: '发送任务', exact: true }).click()
    await expect(page.locator('.message-agent .markdown')).toContainText('GHOST_DESKTOP_OK', { timeout: 90000 })
    await expect.poll(async () => (await page.evaluate(() => window.ghost.snapshot())).runtime.activity).toBe('completed')
    await expect(page.locator('.message-user')).toHaveCount(1)
    await page.screenshot({ path: '.ghost-dev/screenshots/conversation.png' })
    await page.getByRole('button', { name: '打开 Codex 功能中心' }).click()
    const center = page.getByRole('dialog', { name: 'Codex 功能中心' })
    await center.getByRole('button', { name: '读取', exact: true }).click()
    await expect(center.locator('.capability-result')).toContainText('skills', { timeout: 60000 })
    await page.screenshot({ path: '.ghost-dev/screenshots/capabilities.png' })
    await center.locator('.capability-list button').filter({ hasText: 'thread/name/set' }).click()
    await center.getByLabel('name', { exact: true }).fill('GHOST_NATIVE_FEATURES')
    page.once('dialog', dialog => dialog.accept())
    await center.getByRole('button', { name: '执行操作', exact: true }).click()
    await expect.poll(async () => page.evaluate(async () => { const s = await window.ghost.snapshot(); return s.sessions.find(t => t.id === s.settings.lastSessionId)?.title })).toBe('GHOST_NATIVE_FEATURES')
    await center.locator('.capability-groups').getByRole('button', { name: '终端', exact: true }).click()
    await center.getByLabel('终端启动命令').fill("Write-Output 'GHOST_TERMINAL_OK'")
    await center.getByRole('button', { name: '启动终端', exact: true }).click()
    await expect(center.locator('.xterm-screen')).toContainText('GHOST_TERMINAL_OK', { timeout: 60000 })
    await expect(center.getByRole('button', { name: '启动终端', exact: true })).toBeEnabled({ timeout: 60000 })
    await page.screenshot({ path: '.ghost-dev/screenshots/terminal.png' })
    await center.getByRole('button', { name: '关闭功能中心' }).click()
    await page.getByRole('button', { name: '迷你悬浮窗', exact: true }).click()
    const mini = app.windows().find(window => window.url().includes('mini=1'))!
    await expect(mini.locator('.pet-status')).toContainText('任务完成了')
    await expect(mini.locator('.mini-window')).toHaveCount(0)
    const nativePet = await app.evaluate(async ({ BrowserWindow, screen }) => {
      const window = BrowserWindow.getAllWindows().find(w => w.webContents.getURL().includes('mini=1'))!
      const area = screen.getPrimaryDisplay().workArea
      window.setBounds({ x: area.x + area.width - 226, y: area.y + area.height - 266, width: 196, height: 236 })
      return { background: window.getBackgroundColor(), bounds: window.getBounds(), shadow: window.hasShadow(), cornerAlpha: (await window.webContents.capturePage()).toBitmap()[3] }
    })
    expect(nativePet.cornerAlpha).toBe(0)
    expect(nativePet.shadow).toBe(false)
    await mini.screenshot({ path: '.ghost-dev/screenshots/pet.png', omitBackground: true })
    await mini.getByRole('button', { name: '展开桌宠对话' }).click()
    await expect(mini.getByRole('dialog', { name: '与 Ghost 对话' })).toBeVisible()
    await expect(mini.locator('.pet-message.from-ghost').filter({ hasText: 'GHOST_DESKTOP_OK' })).toBeVisible()
    await mini.getByLabel('桌宠消息输入').fill('只回复 GHOST_PET_OK，不调用任何工具。')
    await mini.getByRole('button', { name: '发送桌宠消息' }).click()
    await expect(mini.locator('.pet-message.from-ghost').filter({ hasText: 'GHOST_PET_OK' })).toBeVisible({ timeout: 90000 })
    await expect.poll(async () => (await mini.evaluate(() => window.ghost.snapshot())).runtime.activity).toBe('completed')
    await mini.screenshot({ path: '.ghost-dev/screenshots/pet-chat.png', omitBackground: true })
    await mini.getByRole('button', { name: '收起桌宠对话' }).click()
    await expect(mini.getByRole('dialog', { name: '与 Ghost 对话' })).toHaveCount(0)
    const collapsed = await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(w => w.webContents.getURL().includes('mini=1'))!.getBounds())
    expect(collapsed).toEqual(nativePet.bounds)
    await mini.getByRole('button', { name: '恢复 Ghost 工作台' }).click()
    await expect(page.locator('.message-agent').filter({ hasText: 'GHOST_PET_OK' })).toBeVisible()
    await page.getByLabel('发送给 Ghost 的任务').fill('重启后继续的草稿')
    await expect.poll(async () => page.evaluate(async () => { const s = await window.ghost.snapshot(); return window.ghost.draft(s.settings.lastSessionId!) })).toBe('重启后继续的草稿')
    const last = await page.evaluate(() => window.ghost.snapshot())
    await app.close(); app = null
    app = await electron.launch({ executablePath: require('electron'), args: ['.'], env })
    const restored = await app.firstWindow()
    await expect(restored.getByLabel('发送给 Ghost 的任务')).toHaveValue('重启后继续的草稿')
    expect((await restored.evaluate(() => window.ghost.snapshot())).settings.persona).toContain('你叫 Ghost')
    await restored.evaluate(() => window.ghost.connect())
    await expect(restored.locator('.message-agent .markdown').filter({ hasText: 'GHOST_DESKTOP_OK' })).toBeVisible({ timeout: 60000 })
    expect((await restored.evaluate(() => window.ghost.snapshot())).settings.lastSessionId).toBe(last.settings.lastSessionId)
    await app.evaluate(({ BrowserWindow }) => { BrowserWindow.getAllWindows().find(w => !w.webContents.getURL().includes('mini=1'))!.setContentSize(1366, 768) })
    await restored.getByRole('button', { name: '新建会话' }).click()
    await restored.screenshot({ path: '.ghost-dev/screenshots/home-1366.png' })
    const overflow = await restored.evaluate(() => document.documentElement.scrollWidth > window.innerWidth || document.documentElement.scrollHeight > window.innerHeight)
    expect(overflow).toBe(false)
    expect(errors).toEqual([])
  } catch (error) {
    if (app) {
      const page = app.windows().find(w => !w.url().includes('mini=1'))
      if (page) { await page.screenshot({ path: '.ghost-dev/screenshots/failure.png' }).catch(() => {}); console.log(await page.evaluate(async () => { const s = await window.ghost.snapshot(); return { activity: s.runtime.activity, error: s.runtime.error, connection: s.runtime.connection, session: s.settings.lastSessionId, alerts: [...document.querySelectorAll('[role=alert]')].map(el => el.textContent) } })) }
    }
    throw error
  } finally { await app?.close() }
})
